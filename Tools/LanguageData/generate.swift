// Writes crates/swiftly-vm/src/language_data.rs: the names of every ISO 639-1 / 639-2 language code in
// the three app languages (de, en, ru), as Foundation's CLDR data names them. This is the fallback table of
// the core when the host cannot name a language itself (`LanguageNames`), so a Rust-only host (desktop, tests)
// shows exactly what the Swift app shows.
//
//   DEVELOPER_DIR=/Applications/Xcode.app/Contents/Developer swiftc -O Tools/LanguageData/generate.swift -o /tmp/langdata
//   /tmp/langdata crates/swiftly-vm/src/language_data.rs crates/swiftly-hardening/src/inputs/iso639_codes.txt
//
// Codes: every identifier of `Locale.LanguageCode.isoLanguageCodes` (ISO 639-1 two letters and the 639-2/3
// three letters CLDR names) plus the twenty ISO 639-2 bibliographic codes (`ger`, `fre`, `chi` ...) and the
// complete ISO 639-1 list, so a code that ICU does not list is still asked.
import Foundation

let bibliographic = ["alb", "arm", "baq", "bur", "chi", "cze", "dut", "fre", "geo", "ger", "gre", "ice", "mac", "mao",
                     "may", "per", "rum", "slo", "tib", "wel"]
let iso6391 = """
aa ab ae af ak am an ar as av ay az ba be bg bh bi bm bn bo br bs ca ce ch co cr cs cu cv cy da de dv dz ee el en eo \
es et eu fa ff fi fj fo fr fy ga gd gl gn gu gv ha he hi ho hr ht hu hy hz ia id ie ig ii ik io is it iu ja jv ka kg \
ki kj kk kl km kn ko kr ks ku kv kw ky la lb lg li ln lo lt lu lv mg mh mi mk ml mn mr ms mt my na nb nd ne ng nl nn \
no nr nv ny oc oj om or os pa pi pl ps pt qu rm rn ro ru rw sa sc sd se sg si sk sl sm sn so sq sr ss st su sv sw ta \
te tg th ti tk tl tn to tr ts tt tw ty ug uk ur uz ve vi vo wa wo xh yi yo za zh zu
""".split(whereSeparator: { $0 == " " }).map(String.init)

var codes = Set(Locale.LanguageCode.isoLanguageCodes.map(\.identifier))
codes.formUnion(bibliographic)
codes.formUnion(iso6391)
// ISO 639-2 has a bibliographic and a terminologic code for some languages and Foundation resolves aliases that
// its list does not name (`rus`, `deu`, `fra` ...): ask every two and three letter combination, keep the ones the
// system names.
let letters = Array("abcdefghijklmnopqrstuvwxyz")
let english = Locale(identifier: "en")
for a in letters { for b in letters {
    if english.localizedString(forLanguageCode: "\(a)\(b)") != nil { codes.insert("\(a)\(b)") }
    for c in letters where english.localizedString(forLanguageCode: "\(a)\(b)\(c)") != nil { codes.insert("\(a)\(b)\(c)") }
} }
// Codes that stand for "no language" are handled by the caller before the table is asked.
let sorted = codes.sorted()

func esc(_ s: String) -> String {
    s.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"")
}

let locales = ["de", "en", "ru"].map { Locale(identifier: $0) }
var out = """
//! Generated by `Tools/LanguageData/generate.swift` from Foundation's CLDR names; do not edit by hand.
//! One row per ISO 639-1/639-2 code: code, German, English, Russian name ("" = CLDR has none).

pub(crate) const NAMES: &[(&str, &str, &str, &str)] = &[

"""
var rows = 0
for code in sorted {
    let names = locales.map { $0.localizedString(forLanguageCode: code) ?? "" }
    if names.allSatisfy({ $0.isEmpty }) { continue }
    out += "    (\"\(code)\", \"\(esc(names[0]))\", \"\(esc(names[1]))\", \"\(esc(names[2]))\"),\n"
    rows += 1
}
out += "];\n"
let path = CommandLine.arguments.dropFirst().first ?? "language_data.rs"
try out.write(toFile: path, atomically: true, encoding: .utf8)
print("\(rows) codes of \(sorted.count) -> \(path)")
// Optional second argument: the plain list of all codes asked (also those without a name), one per line. The
// oracle of the hardening crate reads it as its list of real ISO 639-1/639-2 codes.
if CommandLine.arguments.count > 2 {
    try (sorted.joined(separator: "\n") + "\n").write(toFile: CommandLine.arguments[2], atomically: true, encoding: .utf8)
}

import Foundation

/// Short path to a translated string from this package's catalog.
///
/// A package ships its own bundle; without `bundle: .module`, `String(localized:)` looks in
/// the app's bundle and finds nothing.
///
/// **Linux has no `String.LocalizationValue`.** Foundation there knows no string catalogs.
/// The call looks the same on both sides so callers notice nothing; only the path behind it
/// differs: on Linux ``TextCatalog`` and ``Textschluessel`` do by hand what
/// `String.LocalizationValue` does: build the key from the interpolation and find the right
/// `.lproj`.
///
/// **Why it is needed there at all** is explained in `TextCatalog.swift`; in short,
/// `NSLocalizedString` on Linux uses the bundle's development language, not the user's, and
/// a `String` key evaluates the interpolation too early.
///
/// The fallback works because of an early decision: **the German wording is also the key.**
/// If the lookup finds nothing, the result is the German sentence, not `player.error.42`. A
/// missing catalog costs the translation, not readability.
#if canImport(Darwin)
func translated(_ key: String.LocalizationValue) -> String {
    String(localized: key, bundle: .module)
}
#elseif os(Android)
/// **Android has no `Bundle.module`.**
///
/// The accessor generated by SwiftPM looks for the resource bundle next to the executable
/// and otherwise calls `fatalError`; a `.so` has no program directory. Every translated
/// string would have crashed the app, including error messages.
///
/// The Android app unpacks the `.lproj` folders at launch and passes the folder here before
/// any text is needed. If it is missing, the keys are shown: German, readable, no crash.
public enum PackageLanguage {
    nonisolated(unsafe) public static var folder: String?
    nonisolated(unsafe) public static var language: String?
}

let packageCatalog: TextCatalog = {
    guard let folder = PackageLanguage.folder, let bundle = Bundle(path: folder) else {
        return TextCatalog(empty: PackageLanguage.language ?? "de")
    }
    return TextCatalog(bundle: bundle, language: PackageLanguage.language)
}()

func translated(_ key: TextKey) -> String {
    packageCatalog.text(key)
}
#else
/// Read once for the lifetime of the program. A user's language does not change while the
/// app runs.
let packageCatalog = TextCatalog(bundle: .module)

func translated(_ key: TextKey) -> String {
    packageCatalog.text(key)
}
#endif

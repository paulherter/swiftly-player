//! Emits the Rust source of the static catalogue from the parsed sources.

use crate::source::{self, Parsed, RawText, SourceTable};
use std::fmt::Write as _;

fn lit(s: &str) -> String {
    format!("{s:?}")
}

fn text(t: &RawText) -> String {
    match t {
        RawText::Simple(s) => format!("Text::Simple({})", lit(s)),
        RawText::Plural(m) => {
            let forms: Vec<String> = m
                .iter()
                .map(|(c, s)| format!("(C::{c:?}, {})", lit(s)))
                .collect();
            format!("Text::Plural(&[{}])", forms.join(", "))
        }
    }
}

fn origin(o: crate::catalog::Origin) -> &'static str {
    match o {
        crate::catalog::Origin::App => "Origin::App",
        crate::catalog::Origin::Package => "Origin::Package",
        crate::catalog::Origin::Both => "Origin::Both",
    }
}

fn entry(
    out: &mut String,
    key: &str,
    o: crate::catalog::Origin,
    langs: &std::collections::BTreeMap<String, RawText>,
) {
    let items: Vec<String> = langs
        .iter()
        .map(|(l, t)| format!("({}, {})", lit(l), text(t)))
        .collect();
    let _ = writeln!(
        out,
        "    Entry {{ key: {}, origin: {}, langs: &[{}] }},",
        lit(key),
        origin(o),
        items.join(", ")
    );
}

/// The complete text of `src/catalog_data.rs`.
pub fn generate(p: &Parsed) -> String {
    let mut out = String::new();
    out.push_str(
        "// @generated by `cargo run -p swiftly-l10n --bin gen_catalog`. Do not edit.\n\
         // Sources: Sources/Shared/Localizable.xcstrings, Sources/Shared/InfoPlist.xcstrings,\n\
         // Packages/JellyfinKit/Sources/JellyfinKit/Resources/{de,en,ru}.lproj.\n\
         #![allow(clippy::all)]\n\n\
         use crate::catalog::{Catalog, Entry, Origin, SourceStat, Text};\n\
         use crate::plural::PluralCategory as C;\n\n",
    );
    out.push_str("static ENTRIES: &[Entry] = &[\n");
    for (key, e) in &p.merged {
        entry(&mut out, key, e.origin, &e.langs);
    }
    out.push_str("];\n\nstatic INFO_PLIST: &[Entry] = &[\n");
    for (key, langs) in &p.info {
        entry(&mut out, key, crate::catalog::Origin::App, langs);
    }
    out.push_str("];\n\nstatic STATS: &[SourceStat] = &[\n");
    let tables: [(&str, &SourceTable); 4] = [
        ("Localizable.xcstrings", &p.app),
        ("InfoPlist.xcstrings", &p.info),
        ("Localizable.strings", &p.package_strings),
        ("Localizable.stringsdict", &p.package_dict),
    ];
    for (name, table) in tables {
        for lang in source::PACKAGE_LANGS {
            let _ = writeln!(
                out,
                "    SourceStat {{ source: {}, lang: {}, keys: {} }},",
                lit(name),
                lit(lang),
                source::count(table, lang)
            );
        }
    }
    out.push_str("];\n\n/// The generated catalogue.\npub static CATALOG: Catalog = Catalog::new(ENTRIES, INFO_PLIST, STATS);\n");
    out
}

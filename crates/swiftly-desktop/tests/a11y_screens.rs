//! Gate D1 (accessibility), host part: what a screen reader would read on Home, Library, Search, Detail and Player,
//! taken from the tree the AccessKit bridge builds. Set `A11Y_DUMP=<file>` to write the reading lists.
#![allow(clippy::unwrap_used)]

use std::fmt::Write as _;
use swiftly_desktop::a11y_bridge;
use swiftly_desktop::suite::Suite;
use swiftly_layout::Size;
use swiftly_ui::a11y::{A11yNode, Role, spoken};
use swiftly_ui::{Cx, Env, Idiom};

const STEP: f64 = 1000.0 / 60.0;
const SIZE: (f32, f32) = (1280.0, 800.0);

fn run_for(s: &mut Suite, now: &mut f64, ms: f64) {
    let end = *now + ms;
    while *now < end {
        *now += STEP;
        let _ = s.frame(*now);
    }
}

fn flat(nodes: &[A11yNode], depth: usize, out: &mut Vec<(usize, A11yNode)>) {
    for n in nodes {
        out.push((depth, n.clone()));
        flat(&n.children, depth + 1, out);
    }
}

/// The reading list of the screen in front, and a check of the invariants a reader relies on.
fn read(s: &Suite, report: &mut String) -> Vec<(usize, A11yNode)> {
    let (title, nodes) = s.a11y_nodes();
    let mut all = Vec::new();
    flat(&nodes, 0, &mut all);
    let _ = writeln!(report, "\n## {title} ({} nodes)", all.len());
    for (d, n) in &all {
        let _ = writeln!(report, "{}{}", "  ".repeat(*d), spoken(n));
    }
    let built = a11y_bridge::build(title, &nodes, 1.0);
    let update = built.update;
    // Every node id is unique and the focus points at a node of the tree.
    let mut ids: Vec<u64> = update.nodes.iter().map(|(i, _)| i.0).collect();
    let total = ids.len();
    ids.sort_unstable();
    ids.dedup();
    assert_eq!(ids.len(), total, "{title}: duplicate node ids");
    assert!(
        update.nodes.iter().any(|(i, _)| *i == update.focus),
        "{title}: focus is not in the tree"
    );
    for (_, n) in &all {
        if matches!(
            n.role,
            Role::Button | Role::Tab | Role::Switch | Role::Slider
        ) && n.label.trim().is_empty()
        {
            let _ = writeln!(report, "UNNAMED {title}: {:?} at {:?}", n.role, n.bounds);
        }
    }
    all
}

fn tap_node(s: &mut Suite, now: &mut f64, nodes: &[(usize, A11yNode)], label: &str) -> bool {
    let (title, tree) = s.a11y_nodes();
    let built = a11y_bridge::build(title, &tree, 1.0);
    let Some((_, n)) = nodes
        .iter()
        .find(|(_, n)| n.label == label && n.activatable)
    else {
        return false;
    };
    let update = built.update;
    let id = update
        .nodes
        .iter()
        .find(|(_, x)| x.label() == Some(label))
        .map(|(i, _)| i.0);
    let _ = n;
    let Some(&(x, y)) = id.and_then(|i| built.centres.get(&i)) else {
        return false;
    };
    s.touch_down(x, y, *now);
    s.touch_up(x, y, *now + 40.0);
    *now += 80.0;
    true
}

#[test]
fn screens_read_sensibly() {
    let env = Env::new(Size::new(SIZE.0, SIZE.1), 1.0, Idiom::Desktop);
    let mut s = Suite::new(env, Cx::deterministic());
    let mut now = 0.0;
    let mut report =
        String::from("# What a screen reader reads (generated by tests/a11y_screens.rs)\n");
    run_for(&mut s, &mut now, 400.0);

    let home = read(&s, &mut report);
    assert!(home.len() >= 8, "Home exposes only {} nodes", home.len());
    assert!(
        home.iter()
            .any(|(_, n)| n.role == Role::Button && n.activatable),
        "Home has no operable element"
    );

    for (tab, label) in [(1, "Filme"), (2, "Serien"), (3, "Suche")] {
        let nodes = read(&s, &mut String::new());
        if tap_node(&mut s, &mut now, &nodes, label) {
            run_for(&mut s, &mut now, 500.0);
            if s.tab() == tab {
                let list = read(&s, &mut report);
                assert!(
                    list.len() >= 3,
                    "tab {label} exposes only {} nodes",
                    list.len()
                );
            }
        }
    }

    // A tile opens the title page.
    run_for(&mut s, &mut now, 300.0);
    'open: for yi in 0..14 {
        for xi in 0..14 {
            let (x, y) = (
                SIZE.0 * (0.12 + 0.06 * xi as f32),
                SIZE.1 * (0.25 + 0.05 * yi as f32),
            );
            s.touch_down(x, y, now);
            s.touch_up(x, y, now + 40.0);
            now += 80.0;
            if s.title_open() {
                break 'open;
            }
        }
    }
    if s.title_open() {
        run_for(&mut s, &mut now, 1300.0);
        let detail = read(&s, &mut report);
        assert!(
            detail.iter().any(|(_, n)| n.role == Role::Button),
            "Detail has no button"
        );
        'play: for yi in 0..40 {
            for xi in 0..24 {
                let (x, y) = (
                    SIZE.0 * (0.04 + 0.04 * xi as f32),
                    SIZE.1 * (0.08 + 0.022 * yi as f32),
                );
                s.touch_down(x, y, now);
                s.touch_up(x, y, now + 40.0);
                now += 80.0;
                if s.player_open() {
                    break 'play;
                }
            }
        }
        if s.player_open() {
            run_for(&mut s, &mut now, 600.0);
            let player = read(&s, &mut report);
            assert!(
                player.len() >= 3,
                "Player exposes only {} nodes",
                player.len()
            );
        }
    }
    if let Ok(path) = std::env::var("A11Y_DUMP") {
        std::fs::write(path, &report).unwrap();
    }
    let unnamed: Vec<&str> = report
        .lines()
        .filter(|l| l.starts_with("UNNAMED"))
        .collect();
    assert!(
        unnamed.is_empty(),
        "unnamed controls:\n{}",
        unnamed.join("\n")
    );
}

//! Semantic token generator: `design/tokens.json` -> Rust, Swift and Kotlin constants.
//!
//! ```text
//! cargo run -p swiftly-design --bin gen_tokens -- --semantic [--tokens <tokens.json>] \
//!     [--out-rs <file>] [--out-swift <file>] [--out-kt <file>] [--check]
//! ```
//!
//! `tokens.json` is the one source of truth. Entries are named by role (`surface.base`, `radius.control`).
//! The base value is the iPhone value (set `touch`); `desktop` and `tv` override it; `only` limits an entry
//! to some sets. `--check` regenerates in memory and exits 1 when a committed file differs.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use serde_json::Value;

type Result<T> = std::result::Result<T, String>;

const SETS: [&str; 3] = ["touch", "desktop", "tv"];
const GENERATED: &str = "@generated by `cargo run -p swiftly-design --bin gen_tokens -- --semantic` from design/tokens.json. Do not edit by hand.";

#[derive(Clone, Debug)]
enum Item {
    Num(String, f32),
    Text {
        name: String,
        size: f32,
        weight: u16,
        tracking: f32,
        upper: bool,
    },
    Motion {
        name: String,
        curve: String,
        duration: f32,
        response: f32,
        damping: f32,
        scale: Option<f32>,
    },
    Shadow {
        name: String,
        rgba8: u32,
        blur: f32,
        y: f32,
        rest: bool,
    },
}

struct Model {
    colours: Vec<(String, u32)>,
    /// Bezier points of the named curves (`extras.motion.curves`), emitted for Swift and Kotlin.
    curves: Vec<(String, [f32; 4])>,
    sets: BTreeMap<&'static str, Vec<Item>>,
}

fn f(v: f32) -> String {
    format!("{v:?}")
}

fn str_of<'a>(e: &'a Value, key: &str) -> Result<&'a str> {
    e.get(key)
        .and_then(Value::as_str)
        .ok_or_else(|| format!("entry {e}: missing string `{key}`"))
}

fn num_of(e: &Value, key: &str) -> Option<f32> {
    e.get(key).and_then(Value::as_f64).map(|v| v as f32)
}

fn in_set(e: &Value, set: &str) -> bool {
    match e.get("only").and_then(Value::as_array) {
        Some(list) => list.iter().any(|v| v.as_str() == Some(set)),
        None => true,
    }
}

/// The entry with the override of `set` merged over the base fields.
fn merged(e: &Value, set: &str) -> Value {
    let mut base = e.clone();
    if let (Some(obj), Some(Value::Object(over))) = (base.as_object_mut(), e.get(set)) {
        for (k, v) in over {
            obj.insert(k.clone(), v.clone());
        }
    }
    base
}

fn list<'a>(root: &'a Value, key: &str) -> Result<&'a Vec<Value>> {
    root.get(key)
        .and_then(Value::as_array)
        .ok_or_else(|| format!("tokens.json: `{key}` must be a list"))
}

fn rgba8(hex: &str, alpha: f32) -> Result<u32> {
    let h = hex
        .strip_prefix('#')
        .ok_or_else(|| format!("bad colour `{hex}`"))?;
    if h.len() != 6 {
        return Err(format!(
            "colour `{hex}` must be #RRGGBB (alpha is a separate field)"
        ));
    }
    let rgb = u32::from_str_radix(h, 16).map_err(|_| format!("bad colour `{hex}`"))?;
    Ok((rgb << 8) | (alpha.clamp(0.0, 1.0) * 255.0).round() as u32)
}

fn weight(name: &str) -> Result<u16> {
    Ok(match name {
        "regular" => 400,
        "medium" => 500,
        "semibold" => 600,
        "bold" => 700,
        "extrabold" => 800,
        other => return Err(format!("unknown weight `{other}`")),
    })
}

fn build(root: &Value) -> Result<Model> {
    let mut colours = Vec::new();
    for e in list(root, "colors")? {
        let name = str_of(e, "name")?;
        let dark = str_of(e, "dark")?;
        if e.get("light").and_then(Value::as_str) != Some(dark) {
            return Err(format!(
                "colour {name}: the app is dark only, `light` must equal `dark`"
            ));
        }
        let alpha = num_of(e, "alpha").unwrap_or(1.0);
        colours.push((name.to_owned(), rgba8(dark, alpha)?));
    }
    let layout = list(root, "layout")?;
    // The design-tool radius map must agree with the layout table (touch value).
    if let Some(map) = root.get("radius").and_then(Value::as_object) {
        for (k, v) in map {
            let want = format!("radius.{k}");
            let e = layout
                .iter()
                .find(|e| e.get("name").and_then(Value::as_str) == Some(want.as_str()))
                .ok_or_else(|| format!("radius.{k} is in `radius` but not in `layout`"))?;
            if num_of(e, "value") != v.as_f64().map(|x| x as f32) {
                return Err(format!("radius.{k}: `radius` map and `layout` disagree"));
            }
        }
    }
    let mut sets: BTreeMap<&'static str, Vec<Item>> = BTreeMap::new();
    for set in SETS {
        let mut items = Vec::new();
        if let Some(scale) = root.get("spacing").and_then(Value::as_object) {
            let mut steps = Vec::new();
            for (k, v) in scale {
                let v = v.as_f64().ok_or("spacing values must be numbers")? as f32;
                steps.push((k.clone(), v));
            }
            steps.sort_by(|a, b| a.1.total_cmp(&b.1));
            for (k, v) in steps {
                items.push(Item::Num(format!("space.{k}"), v));
            }
        }
        for e in layout.iter().chain(list(root, "state")?) {
            if !in_set(e, set) {
                continue;
            }
            let name = str_of(e, "name")?.to_owned();
            let v = num_of(e, set)
                .or_else(|| num_of(e, "value"))
                .ok_or_else(|| format!("{name}: no value"))?;
            items.push(Item::Num(name, v));
        }
        for e in list(root, "type")? {
            if !in_set(e, set) {
                continue;
            }
            let m = merged(e, set);
            items.push(Item::Text {
                name: str_of(e, "name")?.to_owned(),
                size: num_of(&m, "size").ok_or("type: size missing")?,
                weight: weight(str_of(&m, "weight")?)?,
                tracking: num_of(&m, "tracking").unwrap_or(0.0),
                upper: m.get("uppercase").and_then(Value::as_bool).unwrap_or(false),
            });
        }
        for e in list(root, "motion")? {
            if !in_set(e, set) {
                continue;
            }
            let m = merged(e, set);
            let curve = str_of(&m, "curve")?.to_owned();
            if ![
                "linear",
                "ease-out",
                "ease-in",
                "ease-in-out",
                "smooth",
                "snappy",
                "drawer",
                "spring",
            ]
            .contains(&curve.as_str())
            {
                return Err(format!("unknown curve `{curve}`"));
            }
            items.push(Item::Motion {
                name: str_of(e, "name")?.to_owned(),
                curve,
                duration: num_of(&m, "duration").unwrap_or(0.0),
                response: num_of(&m, "response").unwrap_or(0.0),
                damping: num_of(&m, "damping").unwrap_or(0.0),
                scale: num_of(&m, "scale"),
            });
        }
        for e in list(root, "shadows")? {
            if !in_set(e, set) {
                continue;
            }
            items.push(Item::Shadow {
                name: str_of(e, "name")?.to_owned(),
                rgba8: rgba8(str_of(e, "color")?, num_of(e, "alpha").unwrap_or(1.0))?,
                blur: num_of(e, "blur").ok_or("shadow: blur")?,
                y: num_of(e, "y").ok_or("shadow: y")?,
                rest: e
                    .get("scalesWithRest")
                    .and_then(Value::as_bool)
                    .unwrap_or(false),
            });
        }
        sets.insert(set, items);
    }
    let mut curves = Vec::new();
    if let Some(map) = root
        .get("extras")
        .and_then(|e| e.get("motion"))
        .and_then(|m| m.get("curves"))
        .and_then(Value::as_object)
    {
        for (name, v) in map {
            // Entries that are not four numbers (`linear`: a text) are not bezier curves.
            let Some(a) = v.as_array().filter(|a| a.len() == 4) else {
                continue;
            };
            let mut p = [0.0f32; 4];
            for (i, x) in a.iter().enumerate() {
                p[i] = x.as_f64().ok_or(format!("curve {name}: not a number"))? as f32;
            }
            curves.push((name.clone(), p));
        }
    }
    Ok(Model {
        colours,
        curves,
        sets,
    })
}

fn words(name: &str) -> Vec<String> {
    name.split(['.', '-'])
        .filter(|w| !w.is_empty())
        .map(str::to_owned)
        .collect()
}

fn upper_snake(name: &str) -> String {
    words(name).join("_").to_uppercase()
}

fn lower_camel(name: &str) -> String {
    let mut out = String::new();
    for (i, w) in words(name).iter().enumerate() {
        if i == 0 {
            out.push_str(w);
        } else {
            out.push_str(&w[..1].to_uppercase());
            out.push_str(&w[1..]);
        }
    }
    out
}

fn rust_curve(curve: &str, d: f32, r: f32, z: f32) -> String {
    match curve {
        "linear" => format!("crate::types::Curve::Linear({})", f(d)),
        "ease-out" => format!("crate::types::Curve::EaseOut({})", f(d)),
        "ease-in" => format!("crate::types::Curve::EaseIn({})", f(d)),
        "ease-in-out" => format!("crate::types::Curve::EaseInOut({})", f(d)),
        "smooth" => format!("crate::types::Curve::Smooth({})", f(d)),
        "snappy" => format!("crate::types::Curve::Snappy({})", f(d)),
        "drawer" => format!("crate::types::Curve::Drawer({})", f(d)),
        _ => format!(
            "crate::types::Curve::Spring {{ response: {}, damping: {} }}",
            f(r),
            f(z)
        ),
    }
}

fn rust_colour(v: u32) -> String {
    let ch = |shift: u32| f(((v >> shift) & 0xFF) as f32 / 255.0);
    format!(
        "crate::types::Colour {{ r: {}, g: {}, b: {}, a: {}, rgba8: 0x{v:08X} }}",
        ch(24),
        ch(16),
        ch(8),
        ch(0)
    )
}

fn render_rust(m: &Model) -> String {
    let mut o = String::new();
    let _ = writeln!(o, "// {GENERATED}");
    o.push_str("//! Semantic design tokens, named by role. Same values as `Tokens.generated.swift` and `Tokens.kt`.\n//!\n");
    o.push_str("//! `color` is one value for every layout set; `touch`, `desktop` and `tv` hold spacing, radius, size, state,\n//! type, motion and shadow tokens (the iPhone value is the base, the other sets override it).\n\n");
    o.push_str(
        "/// Colours, one value for every layout set (the app is dark only).\npub mod color {\n",
    );
    for (n, v) in &m.colours {
        let _ = writeln!(
            o,
            "    /// `{n}`.\n    pub const {}: crate::types::Colour = {};",
            upper_snake(n),
            rust_colour(*v)
        );
    }
    o.push_str("}\n");
    for (set, items) in &m.sets {
        let _ = writeln!(
            o,
            "\n/// Tokens of the `{set}` layout set.\npub mod {set} {{"
        );
        for it in items {
            match it {
                Item::Num(n, v) => {
                    let _ = writeln!(
                        o,
                        "    /// `{n}`.\n    pub const {}: f32 = {};",
                        upper_snake(n),
                        f(*v)
                    );
                }
                Item::Text {
                    name,
                    size,
                    weight,
                    tracking,
                    upper,
                } => {
                    let _ = writeln!(
                        o,
                        "    /// `{name}`.\n    pub const TEXT_{}: crate::types::TextStyle = crate::types::TextStyle {{ size: {}, weight: {weight}, tracking: {}, uppercase: {upper} }};",
                        upper_snake(name),
                        f(*size),
                        f(*tracking)
                    );
                }
                Item::Motion {
                    name,
                    curve,
                    duration,
                    response,
                    damping,
                    scale,
                } => {
                    let _ = writeln!(
                        o,
                        "    /// `{name}`.\n    pub const {}: crate::types::Curve = {};",
                        upper_snake(name),
                        rust_curve(curve, *duration, *response, *damping)
                    );
                    if let Some(s) = scale {
                        let _ = writeln!(
                            o,
                            "    /// `{name}` start scale.\n    pub const {}_SCALE: f32 = {};",
                            upper_snake(name),
                            f(*s)
                        );
                    }
                }
                Item::Shadow {
                    name,
                    rgba8,
                    blur,
                    y,
                    rest,
                } => {
                    let _ = writeln!(
                        o,
                        "    /// `{name}`.\n    pub const {}: crate::types::Shadow = crate::types::Shadow {{ colour: {}, blur: {}, y: {}, scales_with_rest: {rest} }};",
                        upper_snake(name),
                        rust_colour(*rgba8),
                        f(*blur),
                        f(*y)
                    );
                }
            }
        }
        o.push_str("}\n");
    }
    o
}

/// One generic renderer for Swift and Kotlin: only names, literals and wrappers differ.
struct Lang {
    line_comment: &'static str,
    open_root: &'static str,
    close_root: &'static str,
    open_obj: fn(&str) -> String,
    konst: fn(name: &str, ty: &str, value: &str) -> String,
    ident: fn(&str) -> String,
    colour: fn(u32) -> (String, &'static str),
    float_ty: &'static str,
    bool_ty: &'static str,
    str_lit: fn(&str) -> String,
}

fn render_generic(m: &Model, l: &Lang) -> String {
    let c = l.line_comment;
    let mut o = String::new();
    let _ = writeln!(o, "{c} {GENERATED}");
    let _ = writeln!(
        o,
        "{c} Semantic design tokens, same values as tokens_generated.rs. Colours are {}.",
        if l.float_ty == "Double" {
            "0xRRGGBBAA"
        } else {
            "0xAARRGGBB"
        }
    );
    o.push_str(&format!("{c} Layout sets: touch (iPhone, iPad, Android phone), desktop (Mac, Windows, Linux), tv (Apple TV; Android TV = half in dp).\n\n"));
    o.push_str(l.open_root);
    let _ = writeln!(o, "{}", (l.open_obj)("Palette").replace("{indent}", "    "));
    for (n, v) in &m.colours {
        let (lit, ty) = (l.colour)(*v);
        let _ = writeln!(o, "{}", indent((l.konst)(&(l.ident)(n), ty, &lit), 2));
    }
    o.push_str("    }\n");
    if !m.curves.is_empty() {
        let _ = writeln!(o, "{}", (l.open_obj)("Curves").replace("{indent}", "    "));
        for (n, p) in &m.curves {
            for (i, axis) in ["x1", "y1", "x2", "y2"].iter().enumerate() {
                let name = (l.ident)(&format!("{n}.{axis}"));
                let _ = writeln!(
                    o,
                    "{}",
                    indent((l.konst)(&name, l.float_ty, &lit(l, p[i])), 2)
                );
            }
        }
        o.push_str("    }\n");
    }
    for (set, items) in &m.sets {
        let cap = format!("{}{}", set[..1].to_uppercase(), &set[1..]);
        let _ = writeln!(o, "{}", (l.open_obj)(&cap));
        let ft = l.float_ty;
        for it in items {
            let mut put = |name: String, ty: &str, v: String| {
                let _ = writeln!(o, "{}", indent((l.konst)(&name, ty, &v), 2));
            };
            match it {
                Item::Num(n, v) => put((l.ident)(n), ft, lit(l, *v)),
                Item::Text {
                    name,
                    size,
                    weight,
                    tracking,
                    upper,
                } => {
                    let base = format!("text.{name}");
                    put((l.ident)(&format!("{base}.size")), ft, lit(l, *size));
                    put(
                        (l.ident)(&format!("{base}.weight")),
                        "Int",
                        weight.to_string(),
                    );
                    put(
                        (l.ident)(&format!("{base}.tracking")),
                        ft,
                        lit(l, *tracking),
                    );
                    put(
                        (l.ident)(&format!("{base}.uppercase")),
                        l.bool_ty,
                        upper.to_string(),
                    );
                }
                Item::Motion {
                    name,
                    curve,
                    duration,
                    response,
                    damping,
                    scale,
                } => {
                    put(
                        (l.ident)(&format!("{name}.curve")),
                        "String",
                        (l.str_lit)(curve),
                    );
                    put(
                        (l.ident)(&format!("{name}.duration")),
                        ft,
                        lit(l, *duration),
                    );
                    put(
                        (l.ident)(&format!("{name}.response")),
                        ft,
                        lit(l, *response),
                    );
                    put((l.ident)(&format!("{name}.damping")), ft, lit(l, *damping));
                    if let Some(s) = scale {
                        put((l.ident)(&format!("{name}.scale")), ft, lit(l, *s));
                    }
                }
                Item::Shadow {
                    name,
                    rgba8,
                    blur,
                    y,
                    rest,
                } => {
                    let (cl, cty) = (l.colour)(*rgba8);
                    put((l.ident)(&format!("{name}.color")), cty, cl);
                    put((l.ident)(&format!("{name}.blur")), ft, lit(l, *blur));
                    put((l.ident)(&format!("{name}.y")), ft, lit(l, *y));
                    put(
                        (l.ident)(&format!("{name}.scales-with-rest")),
                        l.bool_ty,
                        rest.to_string(),
                    );
                }
            }
        }
        o.push_str("    }\n");
    }
    o.push_str(l.close_root);
    o
}

fn lit(l: &Lang, v: f32) -> String {
    if l.float_ty == "Float" {
        format!("{}f", f(v))
    } else {
        f(v)
    }
}

fn indent(s: String, n: usize) -> String {
    format!("{}{s}", "    ".repeat(n))
}

fn swift() -> Lang {
    Lang {
        line_comment: "//",
        open_root: "enum SwiftlyDesignTokens {\n",
        close_root: "}\n",
        open_obj: |n| format!("    enum {n} {{"),
        konst: |n, ty, v| format!("static let {n}: {ty} = {v}"),
        ident: lower_camel,
        colour: |v| (format!("0x{v:08X}"), "UInt32"),
        float_ty: "Double",
        bool_ty: "Bool",
        str_lit: |s| format!("\"{s}\""),
    }
}

fn kotlin() -> Lang {
    Lang {
        line_comment: "//",
        open_root: "package de.paulherter.swiftly.shared\n\nobject DesignTokens {\n",
        close_root: "}\n",
        open_obj: |n| format!("    object {n} {{"),
        konst: |n, ty, v| format!("const val {n}: {ty} = {v}"),
        ident: upper_snake,
        colour: |v| {
            let argb = v.rotate_right(8);
            (format!("0x{argb:08X}L"), "Long")
        },
        float_ty: "Float",
        bool_ty: "Boolean",
        str_lit: |s| format!("\"{s}\""),
    }
}

/// **The colour a platform shows before the app draws its first frame**: the iOS and tvOS launch screen, the Android
/// window background and system splash. Each of them can only name a *resource*, never a Swift or Rust constant, so the
/// resources are generated from `surface.base` here. Before this, the launch colour was a separate hard-coded value
/// (`#101010`) and stayed behind when the ground became `#0A0A0B`; now `--check` fails on any drift.
fn launch_files(m: &Model, repo: &Path) -> Result<Vec<(PathBuf, String)>> {
    let base = m
        .colours
        .iter()
        .find(|(n, _)| n == "surface.base")
        .map(|(_, v)| *v)
        .ok_or_else(|| "tokens.json has no `surface.base`".to_owned())?;
    let (r, g, b) = ((base >> 24) & 0xFF, (base >> 16) & 0xFF, (base >> 8) & 0xFF);
    let colorset = format!(
        r#"{{
  "colors": [
    {{
      "color": {{
        "color-space": "srgb",
        "components": {{
          "alpha": "1.000",
          "blue": "0x{b:02X}",
          "green": "0x{g:02X}",
          "red": "0x{r:02X}"
        }}
      }},
      "idiom": "universal"
    }}
  ],
  "info": {{
    "author": "xcode",
    "version": 1
  }}
}}
"#
    );
    let catalog =
        "{\n  \"info\": {\n    \"author\": \"xcode\",\n    \"version\": 1\n  }\n}\n".to_owned();
    let android = format!(
        "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- @generated by gen_tokens (semantic mode) from design/tokens.json. Do not edit by hand. -->\n<resources>\n    <!-- surface.base: window background and system splash, so the first frame already is the app's ground. -->\n    <color name=\"launch_background\">#FF{r:02X}{g:02X}{b:02X}</color>\n</resources>\n"
    );
    let set = "StartBackground.colorset/Contents.json";
    Ok(vec![
        (
            repo.join("Sources/iOS/Assets.xcassets").join(set),
            colorset.clone(),
        ),
        (
            repo.join("Sources/tvOS/Assets.xcassets").join(set),
            colorset.clone(),
        ),
        (
            repo.join("Sources/RustUI/Assets.xcassets/Contents.json"),
            catalog,
        ),
        (
            repo.join("Sources/RustUI/Assets.xcassets").join(set),
            colorset,
        ),
        (
            repo.join("Android/phone/src/main/res/values/tokens_launch.xml"),
            android.clone(),
        ),
        (
            repo.join("Android/rust-shell/app/src/main/res/values/tokens_launch.xml"),
            android,
        ),
    ])
}

/// Project folders that only the full working tree has: the public snapshot (`scripts/public-paths.txt`) does not carry
/// them, so their generated files cannot be read or written there. An output below one of these folders is checked and
/// written where the folder exists and skipped, with a printed note, where it does not. Every other output stays
/// mandatory: a missing file there is a real error, never a skip.
const PRIVATE_PROJECTS: &[&str] = &["Android/rust-shell"];

/// Drops the outputs of private projects whose folder is not in this tree and says so.
fn present_outputs(outputs: Vec<(PathBuf, String)>, repo: &Path) -> Vec<(PathBuf, String)> {
    outputs
        .into_iter()
        .filter(|(path, _)| {
            let missing = PRIVATE_PROJECTS.iter().find(|project| {
                path.starts_with(repo.join(project)) && !repo.join(project).is_dir()
            });
            if let Some(project) = missing {
                println!(
                    "note: skipped {}: {project} is not part of this tree",
                    path.display()
                );
            }
            missing.is_none()
        })
        .collect()
}

pub struct Args {
    repo: PathBuf,
    tokens: PathBuf,
    out_rs: PathBuf,
    out_swift: PathBuf,
    out_kt: PathBuf,
    check: bool,
}

pub fn parse_args(argv: &[String]) -> Result<Args> {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let repo = root.join("../..");
    let mut a = Args {
        repo: repo.clone(),
        tokens: repo.join("design/tokens.json"),
        out_rs: root.join("src/tokens_generated.rs"),
        out_swift: repo.join("Sources/Shared/Tokens.generated.swift"),
        out_kt: repo.join("Android/shared/src/main/java/de/paulherter/swiftly/shared/Tokens.kt"),
        check: false,
    };
    let mut it = argv.iter();
    while let Some(arg) = it.next() {
        let mut value = |n: &str| {
            it.next()
                .map(PathBuf::from)
                .ok_or_else(|| format!("{n} needs a value"))
        };
        match arg.as_str() {
            "--semantic" => {}
            "--tokens" => a.tokens = value("--tokens")?,
            "--out-rs" => a.out_rs = value("--out-rs")?,
            "--out-swift" => a.out_swift = value("--out-swift")?,
            "--out-kt" => a.out_kt = value("--out-kt")?,
            "--check" => a.check = true,
            other => return Err(format!("unknown argument `{other}` (semantic mode)")),
        }
    }
    Ok(a)
}

pub fn run(a: &Args) -> Result<bool> {
    let text = std::fs::read_to_string(&a.tokens)
        .map_err(|e| format!("cannot read {}: {e}", a.tokens.display()))?;
    let root: Value =
        serde_json::from_str(&text).map_err(|e| format!("{}: {e}", a.tokens.display()))?;
    let model = build(&root)?;
    let mut outputs = vec![
        (a.out_rs.clone(), render_rust(&model)),
        (a.out_swift.clone(), render_generic(&model, &swift())),
        (a.out_kt.clone(), render_generic(&model, &kotlin())),
    ];
    outputs.extend(launch_files(&model, &a.repo)?);
    let outputs = present_outputs(outputs, &a.repo);
    if a.check {
        let mut ok = true;
        for (path, fresh) in &outputs {
            println!("checking {}", path.display());
            match std::fs::read_to_string(path) {
                Ok(old) if old == *fresh => {}
                Ok(_) => {
                    eprintln!("out of date: {}", path.display());
                    ok = false;
                }
                Err(e) => {
                    eprintln!("cannot read {}: {e}", path.display());
                    ok = false;
                }
            }
        }
        if ok {
            println!("semantic tokens up to date ({} outputs)", outputs.len());
        } else {
            eprintln!("run: cargo run -p swiftly-design --bin gen_tokens -- --semantic");
        }
        return Ok(ok);
    }
    for (path, text) in &outputs {
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
        }
        std::fs::write(path, text).map_err(|e| format!("cannot write {}: {e}", path.display()))?;
        println!("wrote {}", path.display());
    }
    Ok(true)
}

#[cfg(test)]
mod launch_tests {
    use super::*;

    #[test]
    fn launch_files_carry_surface_base() {
        let m = Model {
            colours: vec![("surface.base".to_owned(), 0x0A0A_0BFF)],
            curves: vec![],
            sets: BTreeMap::new(),
        };
        let files = launch_files(&m, Path::new("/r")).unwrap();
        assert_eq!(files.len(), 6);
        for (path, text) in &files {
            let p = path.to_string_lossy();
            if p.ends_with("tokens_launch.xml") {
                assert!(text.contains("#FF0A0A0B"), "{p}");
            } else if p.ends_with("StartBackground.colorset/Contents.json") {
                assert!(
                    text.contains("\"red\": \"0x0A\"") && text.contains("\"blue\": \"0x0B\""),
                    "{p}"
                );
            }
        }
    }

    /// A scratch tree under the system temp folder; `name` is fixed per test so a rerun reuses (and first empties) it.
    fn scratch_tree(name: &str) -> PathBuf {
        let tree = std::env::temp_dir().join(format!("swiftly-gen-tokens-{name}"));
        if tree.exists() {
            std::fs::remove_dir_all(&tree).unwrap();
        }
        std::fs::create_dir_all(&tree).unwrap();
        tree
    }

    fn launch_outputs(repo: &Path) -> Vec<(PathBuf, String)> {
        let m = Model {
            colours: vec![("surface.base".to_owned(), 0x0A0A_0BFF)],
            curves: vec![],
            sets: BTreeMap::new(),
        };
        launch_files(&m, repo).unwrap()
    }

    #[test]
    fn a_tree_without_a_private_project_skips_only_its_outputs() {
        // The public snapshot: the shared files are there, `Android/rust-shell` is not.
        let tree = scratch_tree("snapshot");
        let kept = present_outputs(launch_outputs(&tree), &tree);
        assert_eq!(kept.len(), 5);
        assert!(
            kept.iter()
                .all(|(p, _)| !p.starts_with(tree.join("Android/rust-shell")))
        );
        assert!(
            kept.iter()
                .any(|(p, _)| p.starts_with(tree.join("Android/phone")))
        );
    }

    #[test]
    fn a_full_tree_keeps_every_output() {
        let tree = scratch_tree("full");
        std::fs::create_dir_all(tree.join("Android/rust-shell")).unwrap();
        assert_eq!(present_outputs(launch_outputs(&tree), &tree).len(), 6);
    }
}

package de.paulherter.swiftly.shared

import androidx.compose.foundation.Image
import androidx.compose.foundation.layout.requiredSize
import androidx.compose.runtime.Composable
import androidx.compose.ui.Modifier
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.ColorFilter
import androidx.compose.ui.res.painterResource
import androidx.compose.ui.semantics.clearAndSetSemantics
import androidx.compose.ui.semantics.contentDescription
import androidx.compose.ui.unit.Dp

/**
 * **Every symbol in the app comes from here**, phone and TV.
 *
 * The set is **Phosphor Icons, bold** (MIT), the same set and the same mapping as iOS (`IconMap.swift`,
 * generated from the kit's `assets/icons/map.json`). The outline is the bold weight, the solid variant the
 * fill weight; a few own icons keep the same stroke. The vectors and the `Glyph` enum are generated by
 * `Android/tools/phosphor-icons.py`; **no call site picks an icon file**.
 *
 * **`size` is the point size on iPhone**, not the box size. A Phosphor icon fills about 86 % of its
 * 256 grid, so the box is scaled by 1.2 and the glyph stands as tall as the SF Symbol did next to the
 * same text. `Symbol(Glyph.Checkmark, 17.dp)` gives what `.font(.system(size: 17))` shows on iPhone.
 */

/** Kept for the call sites: Phosphor bold has one stroke; the weight no longer changes the drawing. */
enum class Strength(val wght: Int) {
    UltraLight(100), Thin(200), Lightweight(300), Normal(400), Medium(500), Semibold(600), Bold(700)
}

/**
 * One symbol. `size` = the size on iPhone (see above). `description` only where the glyph stands alone;
 * next to a text the text is read. `strength` is accepted for old call sites and ignored.
 */
@Composable
fun Symbol(symbolText: Glyph, size: Dp, modifier: Modifier = Modifier, color: Color = Theme.font,
           @Suppress("UNUSED_PARAMETER") strength: Strength = Strength.Normal,
           filled: Boolean = symbolText.filled, description: String? = null) {
    val box = size * 1.2f
    val res = if (filled) symbolText.fillRes ?: symbolText.outline else symbolText.outline
    Image(painterResource(res), contentDescription = null, colorFilter = ColorFilter.tint(color),
          modifier = modifier.requiredSize(box)
              .clearAndSetSemantics { if (description != null) contentDescription = description })
}

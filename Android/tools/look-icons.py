#!/usr/bin/env python3
"""Android launcher icons for the looks: adaptive-icon vectors from the glass tile template.

The tile (dark glass, mark in the look's gradient with a sheen and a light edge, Halloween's
web) comes from `Assets/SupporterIcons/build-glass.py`: the colors, the mark path and the web
are read from there, so Android never drifts from the other platforms. This script only maps
the 1024 tile onto Android's 108 dp adaptive grid (mark in the inner 72 dp safe zone, as
`build-icons.py` does for the older icons).

    python3 tools/look-icons.py          # from App/Android; writes phone/src/main/res

Per look: `ic_launcher_look_<name>_{background,foreground,monochrome}.xml` and the adaptive
`mipmap-anydpi-v26/ic_launcher_look_<name>{,_round}.xml`. No Chrome and no Pillow rendering is
needed. It prints the manifest aliases to keep in sync.
"""
import importlib.util
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
APP = HERE.parent.parent
RES = HERE.parent / "phone/src/main/res"

spec = importlib.util.spec_from_file_location("glass", APP / "Assets/SupporterIcons/build-glass.py")
glass = importlib.util.module_from_spec(spec)
spec.loader.exec_module(glass)

S = 72 / 1024      # the tile in the safe zone
T = 18             # its offset on the 108 grid
TOKEN = re.compile(r"[MmLlHhVvCcZzQq]|-?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?")


def absolute(d):
    toks = TOKEN.findall(d)
    out, i, cmd = [], 0, None
    x = y = sx = sy = 0.0
    n = {"M": 2, "L": 2, "H": 1, "V": 1, "C": 6, "Q": 4, "Z": 0}
    while i < len(toks):
        if toks[i].isalpha():
            cmd = toks[i]
            i += 1
            if cmd in "Zz":
                out.append(("Z", []))
                x, y = sx, sy
                continue
        up = cmd.upper()
        a = [float(v) for v in toks[i:i + n[up]]]
        i += n[up]
        rel = cmd.islower()
        if up in "ML":
            x, y = (x + a[0], y + a[1]) if rel else (a[0], a[1])
            if up == "M":
                sx, sy = x, y
            out.append((up, [x, y]))
            cmd = "l" if rel else "L" if up == "M" else cmd
        elif up == "H":
            x = x + a[0] if rel else a[0]; out.append(("L", [x, y]))
        elif up == "V":
            y = y + a[0] if rel else a[0]; out.append(("L", [x, y]))
        else:
            k = 6 if up == "C" else 4
            pts = [(x + a[j], y + a[j + 1]) if rel else (a[j], a[j + 1]) for j in range(0, k, 2)]
            out.append((up, [c for p in pts for c in p]))
            x, y = pts[-1]
    return out


def mapped(path):
    parts = []
    for c, a in path:
        pts = [f"{a[k] * S + T:.2f},{a[k + 1] * S + T:.2f}" for k in range(0, len(a), 2)]
        parts.append(c + " ".join(pts))
    return " ".join(parts)


def bbox(path):
    xs = [a[k] for c, a in path for k in range(0, len(a), 2)]
    ys = [a[k + 1] for c, a in path for k in range(0, len(a), 2)]
    return min(xs), min(ys), max(xs), max(ys)


MARK = absolute(glass.MARK)
X0, Y0, X1, Y1 = bbox(MARK)


def px(fx, fy):
    return X0 + (X1 - X0) * fx, Y0 + (Y1 - Y0) * fy


def gradient(kind, p, stops):
    items = "".join(f'\n                <item android:offset="{o}" android:color="{c}" />' for o, c in stops)
    if kind == "linear":
        g = (f'android:type="linear" android:startX="{p[0]:.2f}" android:startY="{p[1]:.2f}" '
             f'android:endX="{p[2]:.2f}" android:endY="{p[3]:.2f}"')
    return f'<gradient {g}>{items}\n            </gradient>'


def aapt(attr, grad):
    return f'\n        <aapt:attr name="android:{attr}">\n            {grad}\n        </aapt:attr>'


def argb(hexcolor, alpha=1.0):
    return f"#{round(alpha * 255):02X}{hexcolor.lstrip('#').upper()}"


def vec(comment, body):
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            f"<!-- {comment} Generated by tools/look-icons.py from Assets/SupporterIcons/build-glass.py, do not edit by hand. -->\n"
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    xmlns:aapt="http://schemas.android.com/aapt"\n'
            '    android:width="108dp" android:height="108dp"\n'
            '    android:viewportWidth="108" android:viewportHeight="108">\n' + body + "\n</vector>\n")


def web_paths():
    """The web of the Halloween tile, as stroke paths on the 108 grid (the template's translate included)."""
    group = glass.WEB
    shift = -22.0 if "translate(-22 -22)" in group else 0.0
    out = []
    for d in re.findall(r'<path d="([^"]+)"', group):
        p = [(c, [v + shift for v in a]) for c, a in absolute(d)]
        out.append(mapped(p))
    return out


def build(name, stops, detail):
    low = f"look_{name.lower()}"
    sx = [px(.2, .15), px(.85, .9)]
    n = len(stops) - 1
    fill_stops = [(f"{i / n:.2f}".rstrip("0").rstrip("."), argb(c)) for i, c in enumerate(stops)]
    fill_stops = [(o if o else "0", c) for o, c in fill_stops]
    mark = mapped(MARK)
    (x1, y1), (x2, y2) = [(a * S + T, b * S + T) for a, b in sx]
    bx0, by0 = X0 * S + T, Y0 * S + T
    by1 = Y1 * S + T
    bx1, bx_r = bx0, X1 * S + T

    bg = ('    <path android:pathData="M0,0 L108,0 L108,108 L0,108 Z">'
          + aapt("fillColor", gradient("linear", (0, 0, 0, 108), [("0", "#FF2C2C31"), ("1", "#FF121214")]))
          + "\n    </path>")
    if detail:
        for d in web_paths():
            bg += (f'\n    <path android:pathData="{d}" android:strokeColor="#33FFFFFF" '
                   f'android:strokeWidth="{5 * S:.2f}" android:strokeLineCap="round" android:strokeLineJoin="round" />')
    fg = (f'    <path android:pathData="{mark}">'
          + aapt("fillColor", gradient("linear", (x1, y1, x2, y2), fill_stops)) + "\n    </path>\n"
          f'    <path android:pathData="{mark}">'
          + aapt("fillColor", gradient("linear", (0, by0, 0, by1), [("0", "#47FFFFFF"), ("0.5", "#00FFFFFF")]))
          + "\n    </path>\n"
          f'    <path android:pathData="{mark}" android:strokeWidth="{9 * S:.2f}">'
          + aapt("strokeColor", gradient("linear", (bx0, by0, bx_r, by1), [("0", "#D9FFFFFF"), ("0.45", "#00FFFFFF")]))
          + "\n    </path>")
    mono = f'    <path android:pathData="{mark}" android:fillColor="#FFFFFFFF" />'
    d = RES / "drawable"
    d.mkdir(parents=True, exist_ok=True)
    (d / f"ic_launcher_{low}_background.xml").write_text(vec(f"Look icon {name}: dark glass tile, opaque.", bg))
    (d / f"ic_launcher_{low}_foreground.xml").write_text(vec(f"Look icon {name}: the mark in the look's gradient.", fg))
    (d / f"ic_launcher_{low}_monochrome.xml").write_text(vec(f"Look icon {name}: silhouette for themed icons.", mono))
    adaptive = ('<?xml version="1.0" encoding="utf-8"?>\n'
                f"<!-- Look icon {name}. Generated by tools/look-icons.py. -->\n"
                '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
                f'    <background android:drawable="@drawable/ic_launcher_{low}_background" />\n'
                f'    <foreground android:drawable="@drawable/ic_launcher_{low}_foreground" />\n'
                f'    <monochrome android:drawable="@drawable/ic_launcher_{low}_monochrome" />\n'
                "</adaptive-icon>\n")
    m = RES / "mipmap-anydpi-v26"
    m.mkdir(parents=True, exist_ok=True)
    for suffix in ("", "_round"):
        (m / f"ic_launcher_{low}{suffix}.xml").write_text(adaptive)


for name, (stops, detail) in glass.TILES.items():
    build(name, stops, detail)
    print("built", name, file=sys.stderr)
for name in glass.TILES:
    print(f'''        <activity-alias
            android:name=".icon.Look{name}"
            android:targetActivity=".MainActivity"
            android:exported="true"
            android:enabled="false"
            android:icon="@mipmap/ic_launcher_look_{name.lower()}"
            android:roundIcon="@mipmap/ic_launcher_look_{name.lower()}_round">
            <intent-filter>
                <action android:name="android.intent.action.MAIN" />
                <category android:name="android.intent.category.LAUNCHER" />
            </intent-filter>
        </activity-alias>''')

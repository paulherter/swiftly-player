#!/usr/bin/env python3
"""Generate the Phosphor (bold) vector drawables and the `Glyph` enum from the design kit.

Source: ~/Library/MochiDoop/kits/swiftly/assets/icons (map.json, phosphor/bold|fill, own/).
Output: Android/shared/.../res/drawable/ph_*.xml and shared/Glyphs.kt. Rerun after the kit's map changes.
"""
import json, os, re, sys
from pathlib import Path

KIT = Path.home() / "Library/MochiDoop/kits/swiftly/assets/icons"
ROOT = Path(__file__).resolve().parents[1] / "shared/src/main"
RES = ROOT / "res/drawable"
KT = ROOT / "java/de/paulherter/swiftly/shared/Glyphs.kt"

# Glyph -> (phosphor name, own?) where map.json has no Android entry or iOS draws an own icon.
EXTRA = {
    "PlayRectangle": "monitor-play", "WlanFrom": "wifi-slash", "StoreLoad": "tray-arrow-down",
    "Computer": "desktop", "EyeOpen": "eye", "DoubleSpeed": "fast-forward", "Cup": "coffee",
}
OWN = {"PlayTv": "tv-play", "SparkleSearch": "magnifying-glass-sparkle", "WaveSearch": "waveform-magnifying-glass",
       "Shadow": "text-shadow", "Pill": "capsule", "SpaceBar": "space-bar", "TextBlock": "text-abc"}
DEFAULT_FILL = {"DoubleSpeed", "Cup"}

m = json.load(open(KIT / "map.json"))
mapped = {}
for r in m["roles"]:
    for u in r["uses"].get("android", []):
        mapped[u["name"]] = (r["phosphor"], r["weight"] == "fill")

src = Path(sys.argv[1]).read_text() if len(sys.argv) > 1 else ""
names = re.findall(r"^\s{4}(\w+)\((?:0x|R\.)", src, re.M) if src else sorted(set(mapped) | set(EXTRA) | set(OWN))

def vector(svg):
    paths = re.findall(r'<path d="([^"]+)"', svg)
    assert paths and "<circle" not in svg and "<rect" not in svg, svg[:80]
    body = "\n".join(f'    <path android:fillColor="#FF000000" android:pathData="{p}"/>' for p in paths)
    return ('<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" '
            'android:height="24dp" android:viewportWidth="256" android:viewportHeight="256">\n' + body + "\n</vector>\n")

RES.mkdir(parents=True, exist_ok=True)
for f in RES.glob("ph_*.xml"): f.unlink()
rows, done = [], set()
for g in names:
    if g in OWN: base, own, fill = OWN[g], True, False
    elif g in EXTRA: base, own, fill = EXTRA[g], False, g in DEFAULT_FILL
    else: base, own = mapped[g][0], False; fill = mapped[g][1]
    res = "ph_" + base.replace("-", "_")
    if res not in done:
        done.add(res)
        svg = (KIT / ("own/%s.svg" % base) if own else KIT / ("phosphor/bold/%s-bold.svg" % base)).read_text()
        (RES / (res + ".xml")).write_text(vector(svg))
    fres = "null"
    if not own and (KIT / ("phosphor/fill/%s-fill.svg" % base)).exists():
        fres = "R.drawable." + res + "_fill"
        if res + "_fill" not in done:
            done.add(res + "_fill")
            (RES / (res + "_fill.xml")).write_text(vector((KIT / ("phosphor/fill/%s-fill.svg" % base)).read_text()))
    rows.append((g, "R.drawable." + res, fres, "true" if fill else "false"))

out = ["package de.paulherter.swiftly.shared", "",
       "// Generated by Android/tools/phosphor-icons.py from the design kit's icon map. Do not edit by hand.", "",
       "/**", " * Every symbol of the app: Phosphor Icons 2.1.1 (MIT), bold for outlines, fill for solid ones; a few own",
       " * icons in the same stroke. Same set and mapping as iOS (`IconMap.swift`). `filled` is the default variant.", " */",
       "enum class Glyph(val outline: Int, val fillRes: Int?, val filled: Boolean) {"]
for g, o, f, d in rows: out.append(f"    {g}({o}, {f}, {d}),")
out += ["    ;", "}", ""]
KT.write_text("\n".join(out))
print(len(rows), "glyphs,", len(done), "drawables")

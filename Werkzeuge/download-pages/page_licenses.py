def anchor(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def row(text):
    """One line of Markdown as HTML: code, bold, links, bare addresses, repo paths."""
    teile, rest = [], text
    muster = re.compile(
        r"\[`?([^\]`]+)`?\]\(([^)]+)\)"          # [Text](Target)
        r"|`([^`]+)`"                            # `Code`
        r"|\*\*([^*]+)\*\*"                      # **bold**
        r"|(https?://[^\s|)]+[^\s|).,;])"        # bare address
        r"|(info@swiftlyplayer\.com)"
        r"|(LICENSES/[A-Za-z0-9.+-]+\.txt)"
        r"|(" + "|".join(re.escape(p) for p in REPO) + r")")
    pos = 0
    for m in muster.finditer(rest):
        teile.append(html.escape(rest[pos:m.start()], quote=False))
        pos = m.end()
        if m.group(1):
            target = m.group(2)
            if target.startswith("LICENSES/"):
                target = "/licenses/" + target.split("/", 1)[1]
            teile.append(f'<a href="{html.escape(target)}">{html.escape(m.group(1).replace("LICENSES/", ""))}</a>')
        elif m.group(3):
            word = m.group(3)
            if word == "LICENSE":
                teile.append(f'<a href="{GITHUB}/blob/main/LICENSE" target="_blank" rel="noopener"><code>LICENSE</code></a>')
            elif word == "LICENSES/":
                teile.append('<a href="#license-texts">the list below</a>')
            else:
                teile.append(f"<code>{html.escape(word)}</code>")
        elif m.group(4):
            teile.append(f"<strong>{row(m.group(4))}</strong>")
        elif m.group(5):
            u = html.escape(m.group(5))
            teile.append(f'<a href="{u}" target="_blank" rel="noopener">{u.split("://", 1)[1].rstrip("/")}</a>')
        elif m.group(6):
            teile.append(f'<a href="mailto:{m.group(6)}">{m.group(6)}</a>')
        elif m.group(7):
            name = m.group(7).split("/", 1)[1]
            teile.append(f'<a href="/licenses/{name}">{name}</a>')
        else:
            path = m.group(8)
            foreign = "" if REPO[path].startswith("/") else ' target="_blank" rel="noopener"'
            teile.append(f'<a href="{REPO[path]}"{foreign}>{html.escape(path)}</a>')
    teile.append(html.escape(rest[pos:], quote=False))
    return "".join(teile)


def table(rows):
    header_cells = [z.strip() for z in rows[0].strip("|").split("|")]
    fromValue = ['    <div class="lz-tabelle"><table>', "      <thead><tr>"
           + "".join(f"<th scope=\"col\">{html.escape(k)}</th>" for k in header_cells) + "</tr></thead>", "      <tbody>"]
    for z in rows[2:]:
        cells = [c.strip() for c in z.strip().strip("|").split("|")]
        fromValue.append("        <tr>" + "".join(
            (f'<th scope="row" data-k="{html.escape(header_cells[i])}">{row(c)}</th>' if i == 0
             else f'<td data-k="{html.escape(header_cells[i])}">{row(c)}</td>')
            for i, c in enumerate(cells)) + "</tr>")
    fromValue += ["      </tbody>", "    </table></div>"]
    return "\n".join(fromValue)


def set(text):
    """The notices file as page sections. Returns (intro, html)."""
    rows = text.splitlines()
    intro, fromValue, i, opened = "", [], 0, False
    while i < len(rows):
        z = rows[i]
        if not z.strip():
            i += 1
            continue
        if z.startswith("# "):
            i += 1
            continue
        if z.startswith("## "):
            title = z[3:].strip()
            if opened:
                fromValue.append("  </section>\n")
            identifier = anchor(title)
            fromValue.append(f'  <section class="abschnitt lz" aria-labelledby="{identifier}">\n    <h2 id="{identifier}">{row(title)}</h2>')
            opened = True
            i += 1
        elif z.startswith("### "):
            title = z[4:].strip()
            fromValue.append(f'    <h3 id="{anchor(title)}">{row(title)}</h3>')
            i += 1
        elif z.startswith("|"):
            block = []
            while i < len(rows) and rows[i].startswith("|"):
                block.append(rows[i])
                i += 1
            fromValue.append(table(block))
        elif z.startswith("- "):
            points = []
            while i < len(rows) and rows[i].startswith("- "):
                points.append(f"      <li>{row(rows[i][2:].strip())}</li>")
                i += 1
            fromValue.append('    <ul class="lz-liste">\n' + "\n".join(points) + "\n    </ul>")
        else:
            paragraph = []
            while i < len(rows) and rows[i].strip() and not rows[i].startswith(("#", "|", "- ")):
                paragraph.append(rows[i].strip())
                i += 1
            whole = " ".join(paragraph)
            if not opened:
                # The sentence about how the file is generated applies to the repository, not the page.
                intro = re.sub(r"\s*This file is generated.*$", "", whole)
            elif whole == "Notes:":
                fromValue.append('    <p class="lz-notiz">Notes</p>')
            else:
                fromValue.append(f"    <p>{row(whole)}</p>")
    if opened:
        fromValue.append("  </section>\n")
    return intro, "\n".join(fromValue)


